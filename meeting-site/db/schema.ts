import { sql } from "drizzle-orm";
import { integer, sqliteTable, text } from "drizzle-orm/sqlite-core";

export const meetingEntries = sqliteTable("meeting_entries", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  formVersion: text("form_version").notNull().default("legacy-v8"),
  participationChoices: text("participation_choices").notNull().default(""),
  category: text("category").notNull(),
  topic: text("topic").notNull(),
  role: text("role").notNull().default("ไม่ระบุบทบาท"),
  reporter: text("reporter").notNull().default("ไม่ระบุชื่อ"),
  testedWork: text("tested_work").notNull().default(""),
  deviceBrowser: text("device_browser").notNull().default(""),
  testResult: text("test_result").notNull().default("ยังไม่ได้ตรวจ"),
  stakeholderGroup: text("stakeholder_group").notNull().default(""),
  participatedProblemDefinition: integer("participated_problem_definition").notNull().default(0),
  participatedDataReview: integer("participated_data_review").notNull().default(0),
  participatedSystemTrial: integer("participated_system_trial").notNull().default(0),
  participatedDecision: integer("participated_decision").notNull().default(0),
  participatedImplementation: integer("participated_implementation").notNull().default(0),
  participatedFollowup: integer("participated_followup").notNull().default(0),
  educationBenefitScore: integer("education_benefit_score").notNull().default(0),
  transportBenefitScore: integer("transport_benefit_score").notNull().default(0),
  networkBenefitScore: integer("network_benefit_score").notNull().default(0),
  participationScore: integer("participation_score").notNull().default(0),
  researchUseAcknowledged: integer("research_use_acknowledged").notNull().default(0),
  observedIssueOptions: text("observed_issue_options").notNull().default(""),
  improvementChoice: text("improvement_choice").notNull().default(""),
  issue: text("issue").notNull().default(""),
  proposal: text("proposal").notNull().default(""),
  decision: text("decision").notNull().default(""),
  conclusion: text("conclusion").notNull().default(""),
  owner: text("owner").notNull().default(""),
  dueDate: text("due_date").notNull().default(""),
  status: text("status").notNull().default("รอพิจารณา"),
  createdAt: text("created_at").notNull().default(sql`CURRENT_TIMESTAMP`),
});
